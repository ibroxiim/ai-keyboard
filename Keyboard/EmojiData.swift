/// Recently used emoji, most recent first. The extension's own defaults — works without Full Access.
enum EmojiRecents {
    private static let key = "emojiRecents"
    private static let limit = 32

    static var all: [String] { UserDefaults.standard.stringArray(forKey: key) ?? [] }

    static func add(_ emoji: String) {
        var list = all
        list.removeAll { $0 == emoji }
        list.insert(emoji, at: 0)
        UserDefaults.standard.set(Array(list.prefix(limit)), forKey: key)
    }
}
